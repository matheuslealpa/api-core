package io.github.matheuslealpa.apicore.jpa;

import java.time.Instant;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.Version;

import org.jspecify.annotations.Nullable;

import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedBy;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

/**
 * Superclass with auditing fields and optimistic locking, for entities that define their own id.
 * Subclasses can use Lombok's {@code @SuperBuilder}: the builder exposes only the subclass fields.
 */
@MappedSuperclass
@EntityListeners(AuditingEntityListener.class)
public abstract class AuditableEntity {

    @Version
    private @Nullable Long version;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private @Nullable Instant createdAt;

    @CreatedBy
    @Column(name = "created_by", updatable = false)
    private @Nullable String createdBy;

    @LastModifiedDate
    @Column(name = "updated_at")
    private @Nullable Instant updatedAt;

    @LastModifiedBy
    @Column(name = "updated_by")
    private @Nullable String updatedBy;

    protected AuditableEntity() {
    }

    protected AuditableEntity(AuditableEntityBuilder<?, ?> builder) {
    }

    public @Nullable Long getVersion() {
        return version;
    }

    public @Nullable Instant getCreatedAt() {
        return createdAt;
    }

    public @Nullable String getCreatedBy() {
        return createdBy;
    }

    public @Nullable Instant getUpdatedAt() {
        return updatedAt;
    }

    public @Nullable String getUpdatedBy() {
        return updatedBy;
    }

    /**
     * Root of the builder hierarchy generated by Lombok's {@code @SuperBuilder} in subclasses.
     * Auditing, version and id fields are managed by JPA and intentionally not exposed.
     */
    public abstract static class AuditableEntityBuilder<C extends AuditableEntity, B extends AuditableEntityBuilder<C, B>> {

        protected abstract B self();

        public abstract C build();
    }
}
